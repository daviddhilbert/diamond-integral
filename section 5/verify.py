def lean_declaration_text(source):
    # Exclude nested Lean block comments from public-declaration discovery.
    result, depth, i = [], 0, 0
    while i < len(source):
        if source.startswith('/-', i):
            depth += 1
            result.append('  ')
            i += 2
        elif depth and source.startswith('-/', i):
            depth -= 1
            result.append('  ')
            i += 2
        else:
            result.append(source[i] if depth == 0 or source[i] == '\n' else ' ')
            i += 1
    return ''.join(result)

